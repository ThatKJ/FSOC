int failures = 0;

void check(const bool condition, const std::string_view expression, const int line) {
    if (!condition) {
        ++failures;
        std::cerr << "FAIL line " << line << ": " << expression << '\n';
    }
}

void check_near(
    const double actual, const double expected, const double tolerance,
    const std::string_view expression, const int line) {
    if (!(std::abs(actual - expected) <= tolerance)) {
        ++failures;
        std::cerr << "FAIL line " << line << ": " << expression << " actual=" << actual
                  << " expected=" << expected << " tol=" << tolerance << '\n';
    }
}

template <typename Fn>
void check_throws_invalid_argument(Fn&& fn, const std::string_view expression, const int line) {
    bool threw = false;
    try {
        std::forward<Fn>(fn)();
    } catch (const std::invalid_argument&) {
        threw = true;
    } catch (...) {
        // wrong exception type is still a failure
    }
    check(threw, expression, line);
}

template <typename Fn>
void check_throws_runtime_error(Fn&& fn, const std::string_view expression, const int line) {
    bool threw = false;
    try {
        std::forward<Fn>(fn)();
    } catch (const std::runtime_error&) {
        threw = true;
    } catch (...) {
    }
    check(threw, expression, line);
}

#define CHECK(expr) check((expr), #expr, __LINE__)
#define CHECK_NEAR(actual, expected, tol) \
    check_near((actual), (expected), (tol), #actual " ~= " #expected, __LINE__)
#define CHECK_THROWS_INVALID(expr) \
    check_throws_invalid_argument([&] { (void)(expr); }, #expr, __LINE__)
#define CHECK_THROWS_RUNTIME(expr) \
    check_throws_runtime_error([&] { (void)(expr); }, #expr, __LINE__)

// ---------------------------------------------------------------------------
// Minimal ad-hoc JSON scalar/array reader for the flat fixture file this test
// consumes (tests/fixtures/ai_parity/expected.json). Deliberately NOT a
// general JSON parser -- the fixture is machine-generated by json.dumps
// (tools/ai/make_parity_fixture.py) with a fixed, known, purely-numeric
// shape, so adding a full JSON dependency for it would be unjustified
// (CLAUDE.md: no unnecessary dependencies; Stage-3 prompt §40).
// ---------------------------------------------------------------------------

[[nodiscard]] std::string read_file(const std::string& path) {
    std::ifstream in(path, std::ios::binary);
    if (!in.good()) {
        throw std::runtime_error("cannot read file: " + path);
    }
    std::ostringstream ss;
    ss << in.rdbuf();
    return ss.str();
}

[[nodiscard]] bool is_number_char(const char c) {
    return std::isdigit(static_cast<unsigned char>(c)) != 0 || c == '-' || c == '+' || c == '.' ||
           c == 'e' || c == 'E';
}

[[nodiscard]] double read_json_number(const std::string& text, const std::string& key) {
    const std::string needle = "\"" + key + "\":";
    const auto key_pos = text.find(needle);
    if (key_pos == std::string::npos) {
        throw std::runtime_error("JSON key not found: " + key);
    }
    std::size_t pos = key_pos + needle.size();
    while (pos < text.size() && std::isspace(static_cast<unsigned char>(text[pos]))) {
        ++pos;
    }
    std::size_t end = pos;
    while (end < text.size() && is_number_char(text[end])) {
        ++end;
    }
    return std::stod(text.substr(pos, end - pos));
}

// Returns every number found inside the (possibly nested) JSON array value of
// `key`, in textual (row-major) order.
[[nodiscard]] std::vector<double> read_json_number_array(const std::string& text, const std::string& key) {
    const std::string needle = "\"" + key + "\":";
    const auto key_pos = text.find(needle);
    if (key_pos == std::string::npos) {
        throw std::runtime_error("JSON key not found: " + key);
    }
    const auto open = text.find('[', key_pos);
    if (open == std::string::npos) {
        throw std::runtime_error("JSON array not found for key: " + key);
    }
    int depth = 0;
    std::size_t close = std::string::npos;
    for (std::size_t i = open; i < text.size(); ++i) {
        if (text[i] == '[') {
            ++depth;
        } else if (text[i] == ']') {
            --depth;
            if (depth == 0) {
                close = i;
                break;
            }
        }
    }
    if (close == std::string::npos) {
        throw std::runtime_error("unterminated JSON array for key: " + key);
    }

    std::vector<double> values;
    std::size_t i = open + 1;
    while (i < close) {
        if (is_number_char(text[i]) &&
            (std::isdigit(static_cast<unsigned char>(text[i])) != 0 || text[i] == '-')) {
            std::size_t j = i;
            while (j < close && is_number_char(text[j])) {
                ++j;
            }
            values.push_back(std::stod(text.substr(i, j - i)));
            i = j;
        } else {
            ++i;
        }
    }
    return values;
}

// ---- paths ---------------------------------------------------------------

[[nodiscard]] std::string project_root() { return FSOC_PROJECT_SOURCE_DIR; }
[[nodiscard]] std::string model_path() { return project_root() + "/models/tiny_beacon_net.onnx"; }
[[nodiscard]] std::string fixture_dir() { return project_root() + "/tests/fixtures/ai_parity/"; }

[[nodiscard]] AiBeaconDetectorConfig default_config() {
    AiBeaconDetectorConfig config{};
    config.model_path = model_path();
    config.presence_threshold = 0.95;  // models/threshold.json (frozen)
    return config;
}

// A detector with threshold 0.0 always returns a value (used for parity /
// robustness checks that need the raw decoded output regardless of presence).
[[nodiscard]] AiBeaconDetectorConfig unthresholded_config() {
    AiBeaconDetectorConfig config = default_config();
    config.presence_threshold = 0.0;
    return config;
}

