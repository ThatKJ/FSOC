// ---- 4. invalid presence threshold rejected --------------------------

void test_invalid_presence_threshold_rejected() {
    AiBeaconDetectorConfig negative = default_config();
    negative.presence_threshold = -0.1;
    CHECK_THROWS_INVALID(AiBeaconDetector{negative});

    AiBeaconDetectorConfig too_high = default_config();
    too_high.presence_threshold = 1.1;
    CHECK_THROWS_INVALID(AiBeaconDetector{too_high});

    AiBeaconDetectorConfig nan_threshold = default_config();
    nan_threshold.presence_threshold = std::nan("");
    CHECK_THROWS_INVALID(AiBeaconDetector{nan_threshold});

    // Boundary-valid thresholds must NOT throw.
    bool ok = true;
    try {
        AiBeaconDetectorConfig lo = default_config();
        lo.presence_threshold = 0.0;
        const AiBeaconDetector d_lo{lo};
        AiBeaconDetectorConfig hi = default_config();
        hi.presence_threshold = 1.0;
        const AiBeaconDetector d_hi{hi};
        (void)d_lo;
        (void)d_hi;
    } catch (...) {
        ok = false;
    }
    CHECK(ok);
}

